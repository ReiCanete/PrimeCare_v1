let currentReportData = null;

document.addEventListener('DOMContentLoaded', async () => {
    if (await checkAccess()) {
        setRange('month');
    }
});

window.addEventListener('primecare:rolechange', async () => {
    await checkAccess();
});

async function checkAccess() {
    const user = await api.getCurrentUser();
    if (!user || user.role !== 'admin') {
        document.getElementById('access-denied').style.display = 'block';
        document.getElementById('reports-module').style.display = 'none';
        return false;
    }
    document.getElementById('access-denied').style.display = 'none';
    document.getElementById('reports-module').style.display = 'block';
    return true;
}

window.setRange = function(range) {
    const today = new Date();
    const toStr = today.toLocaleDateString('en-CA');
    let fromStr = toStr;

    if (range === 'week') {
        const from = new Date(today);
        from.setDate(today.getDate() - today.getDay()); // Sunday
        fromStr = from.toLocaleDateString('en-CA');
    } else if (range === 'month') {
        const from = new Date(today.getFullYear(), today.getMonth(), 1);
        fromStr = from.toLocaleDateString('en-CA');
    }

    document.getElementById('r-from').value = fromStr;
    document.getElementById('r-to').value = toStr;
};

window.generateReport = async function() {
    const type = document.getElementById('r-type').value;
    const typeText = document.getElementById('r-type').options[document.getElementById('r-type').selectedIndex].text;
    const dateFrom = document.getElementById('r-from').value;
    const dateTo = document.getElementById('r-to').value;

    if (!dateFrom || !dateTo) return utils.showAlert('alert-container', 'danger', 'Please select a date range.');
    if (dateFrom > dateTo) return utils.showAlert('alert-container', 'danger', 'Date From cannot be after Date To.');

    const res = await api.generateReport(type, { dateFrom, dateTo });
    if (res.success) {
        currentReportData = { title: typeText, ...res };
        await renderReport(typeText, dateFrom, dateTo, res);
        utils.showToast('Report generated successfully.', 'success');
    } else {
        utils.showAlert('alert-container', 'danger', res.message);
    }
};

async function renderReport(title, dateFrom, dateTo, data) {
    document.getElementById('report-output').style.display = 'block';
    document.getElementById('out-title').innerText = title;
    document.getElementById('out-dates').innerText = `Period: ${utils.formatDate(dateFrom)} to ${utils.formatDate(dateTo)}`;

    const sumDiv = document.getElementById('out-summary');
    sumDiv.innerHTML = Object.keys(data.summary).map(key => `
        <div class="card stat-card" style="margin-bottom: 0; padding: 1rem; border: 1px solid var(--color-border); box-shadow: none;">
            <h3 style="font-size: var(--fs-xs);">${key}</h3>
            <div class="value" style="font-size: var(--fs-xl); color: var(--color-primary);">${typeof data.summary[key] === 'number' && key.includes('Revenue') ? utils.formatCurrency(data.summary[key]) : data.summary[key]}</div>
        </div>
    `).join('');

    const chartDiv = document.getElementById('out-chart');
    if (data.chartData && data.chartData.length > 0) {
        chartDiv.style.display = 'flex';
        const maxVal = Math.max(...data.chartData.map(d => d.value), 1);
        chartDiv.innerHTML = data.chartData.map(d => {
            const pct = (d.value / maxVal) * 100;
            return `
            <div class="chart-col">
                <div style="font-size: var(--fs-xs); font-weight: bold; color: var(--color-primary); margin-bottom: var(--space-4);">${d.value}</div>
                <div class="chart-bar" style="height: ${pct}%;"></div>
                <div class="chart-label" title="${d.label}">${d.label}</div>
            </div>`;
        }).join('');
    } else {
        chartDiv.style.display = 'none';
    }

    const thead = document.getElementById('out-thead');
    const tbody = document.getElementById('out-tbody');
    thead.innerHTML = `<tr>${data.columns.map(c => `<th>${c}</th>`).join('')}</tr>`;
    
    if (data.rows.length === 0) {
        tbody.innerHTML = `<tr><td colspan="${data.columns.length}" style="text-align: center; padding: 2rem; color: var(--color-text-muted);">No data for this period.</td></tr>`;
    } else {
        tbody.innerHTML = data.rows.map(row => `
            <tr>${row.map(cell => {
                const content = (typeof cell === 'number' && title.includes('Revenue') && cell > 100) ? utils.formatCurrency(cell) : utils.escapeHTML(cell);
                return `<td>${content}</td>`;
            }).join('')}</tr>
        `).join('');
    }

    const user = await api.getCurrentUser();
    document.getElementById('out-footer').innerText = `Generated by ${user.fullName} (${user.role}) on ${utils.formatDateTime(new Date().toISOString())}`;
}

window.exportCSV = function() {
    if (!currentReportData || currentReportData.rows.length === 0) return utils.showToast('No data to export.', 'warning');
    
    let csvContent = "data:text/csv;charset=utf-8,";
    // Header
    csvContent += currentReportData.columns.join(",") + "\n";
    // Rows
    currentReportData.rows.forEach(row => {
        let rowStr = row.map(cell => {
            let str = String(cell);
            if (str.includes(',')) str = `"${str}"`;
            return str;
        }).join(",");
        csvContent += rowStr + "\n";
    });

    const encodedUri = encodeURI(csvContent);
    const link = document.createElement("a");
    link.setAttribute("href", encodedUri);
    link.setAttribute("download", `${currentReportData.title.replace(/\s+/g, '_')}_${new Date().toISOString().split('T')[0]}.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
};